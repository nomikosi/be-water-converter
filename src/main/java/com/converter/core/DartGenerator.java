package com.converter.core;

import com.fasterxml.jackson.databind.JsonNode;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Generates Dart classes with {@code fromJson} and {@code toJson} from a JSON
 * structure.
 *
 * <p>The conversion code is written out rather than generated by
 * json_serializable, so the classes need no build step and no package: they
 * read what {@code jsonDecode} returns and give {@code jsonEncode} what it
 * writes. Fields are final and lowerCamelCase, each read from and written to
 * its own key. A key the example showed absent or null in some element is
 * nullable and left out of {@code toJson} when null; a value seen only as null,
 * or elements of different kinds, is {@code dynamic}.
 */
public class DartGenerator {

    /** Name of the generated root class. */
    public static final String ROOT_TYPE_NAME = "Root";

    /** dart:core types the output names, or code beside it likely does, which a class would shadow. */
    static final Set<String> RESERVED_TYPE_NAMES = Set.of(
          "BigInt", "DateTime", "Duration", "Enum", "Error", "Exception", "Function", "Future",
          "Iterable", "List", "Map", "MapEntry", "Never", "Null", "Object", "Record", "RegExp", "Set",
          "Stream", "String", "Symbol", "Type", "Uri");

    /**
     * Reserved words and built-in identifiers, the members every object has,
     * and the two this output adds: none can be a field's name.
     */
    static final Set<String> RESERVED_FIELD_NAMES = Set.of(
          "abstract", "as", "assert", "async", "await", "break", "case", "catch", "class", "const",
          "continue", "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export",
          "extends", "extension", "external", "factory", "false", "final", "finally", "for",
          "function", "get", "hashCode", "if", "implements", "import", "in", "interface", "is",
          "late", "library", "mixin", "new", "noSuchMethod", "null", "operator", "part", "required",
          "rethrow", "return", "runtimeType", "set", "static", "super", "switch", "this", "throw",
          "toString", "true", "try", "typedef", "var", "void", "while", "with", "yield",
          "fromJson", "toJson");

    /** How a value is typed, read and written. */
    private enum Kind { INT, DOUBLE, NUM, STRING, BOOL, DYNAMIC, MAP, CLASS, LIST }

    private record DartType(Kind kind, String className, DartType element, boolean nullable) {
        DartType orNull() {
            return nullable || kind == Kind.DYNAMIC ? this : new DartType(kind, className, element, true);
        }

        String declared() {
            String base = switch (kind) {
                case INT -> "int";
                case DOUBLE -> "double";
                case NUM -> "num";
                case STRING -> "String";
                case BOOL -> "bool";
                case DYNAMIC -> "dynamic";
                case MAP -> "Map<String, dynamic>";
                case CLASS -> className;
                case LIST -> "List<" + element.declared() + ">";
            };
            return nullable && kind != Kind.DYNAMIC ? base + "?" : base;
        }
    }

    public String fromJson(String json) throws Exception {
        if (json == null || json.isBlank())
            throw new IllegalArgumentException("Input must not be null or blank");
        StructureModel model = StructureModel.from(GeneratorJson.readTree(json), ROOT_TYPE_NAME,
              SourceConventions::typeNameFromWords, RESERVED_TYPE_NAMES);
        StringBuilder out = new StringBuilder();
        for (Map.Entry<String, JsonNode> type : model.types().entrySet()) {
            if (!out.isEmpty()) out.append('\n');
            declare(type.getKey(), type.getValue(), model, out);
        }
        return out.toString();
    }

    private record Field(String key, String name, DartType type, boolean optional) {}

    private static void declare(String name, JsonNode object, StructureModel model, StringBuilder out) {
        List<Field> fields = new ArrayList<>();
        Set<String> used = new LinkedHashSet<>();
        for (Map.Entry<String, JsonNode> property : object.properties()) {
            boolean optional = model.isOptional(object, property.getKey());
            DartType type = typeOf(property.getValue(), model);
            fields.add(new Field(property.getKey(), SourceConventions.uniqueName(fieldName(property.getKey()), "", used),
                  optional ? type.orNull() : type, optional));
        }

        out.append("class ").append(name).append(" {\n");
        for (Field field : fields)
            out.append("  final ").append(field.type().declared()).append(' ').append(field.name()).append(";\n");
        if (!fields.isEmpty()) out.append('\n');

        // The constructor: every field named, and required unless it may be null.
        if (fields.isEmpty()) {
            out.append("  const ").append(name).append("();\n\n");
        } else {
            out.append("  const ").append(name).append("({\n");
            for (Field field : fields)
                out.append("    ").append(field.optional() ? "" : "required ").append("this.").append(field.name()).append(",\n");
            out.append("  });\n\n");
        }

        out.append("  factory ").append(name).append(".fromJson(Map<String, dynamic> json) => ");
        if (fields.isEmpty()) {
            out.append("const ").append(name).append("();\n\n");
        } else {
            out.append(name).append("(\n");
            for (Field field : fields)
                out.append("        ").append(field.name()).append(": ")
                      .append(read(field.type(), "json[" + stringLiteral(field.key()) + "]", 0)).append(",\n");
            out.append("      );\n\n");
        }

        out.append("  Map<String, dynamic> toJson() => {");
        if (fields.isEmpty()) {
            out.append("};\n");
        } else {
            out.append('\n');
            for (Field field : fields) {
                String key = stringLiteral(field.key());
                if (field.optional()) {
                    // Left out when null, as the example had it, rather than written
                    // as null. A public field is not promoted by the test, hence the !.
                    DartType present = new DartType(field.type().kind(), field.type().className(),
                          field.type().element(), false);
                    String value = write(present, field.name() + "!", 0);
                    out.append("        if (").append(field.name()).append(" != null) ").append(key).append(": ")
                          .append(value == null ? field.name() : value).append(",\n");
                } else {
                    String value = write(field.type(), field.name(), 0);
                    out.append("        ").append(key).append(": ").append(value == null ? field.name() : value)
                          .append(",\n");
                }
            }
            out.append("      };\n");
        }
        out.append("}\n");
    }

    /** {@code firstName}; {@code value} for a key without letters or digits, and {@code classValue} for a reserved word. */
    static String fieldName(String key) {
        String name = SourceConventions.lowerCamelCase(key);
        if (name.isEmpty()) return "value";
        // Not an underscore: a named parameter cannot start with one, and a
        // name that does is private to its library.
        if (Character.isDigit(name.charAt(0))) return "field" + name;
        return RESERVED_FIELD_NAMES.contains(name) ? name + "Value" : name;
    }

    private static DartType typeOf(JsonNode node, StructureModel model) {
        if (node.isInt() || node.isShort() || node.isLong()) return new DartType(Kind.INT, null, null, false);
        // jsonDecode reads a whole number past 64 bits as a double.
        if (node.isBigInteger()) return new DartType(Kind.NUM, null, null, false);
        if (node.isNumber()) return new DartType(Kind.DOUBLE, null, null, false);
        if (node.isBoolean()) return new DartType(Kind.BOOL, null, null, false);
        if (node.isTextual()) return new DartType(Kind.STRING, null, null, false);
        if (node.isObject()) {
            String name = model.nameOf(node);
            return name != null ? new DartType(Kind.CLASS, name, null, false) : new DartType(Kind.MAP, null, null, false);
        }
        if (node.isArray()) {
            JsonNode element = model.elementOf(node);
            DartType type = element == null ? new DartType(Kind.DYNAMIC, null, null, false) : typeOf(element, model);
            if (model.hasNullElement(node)) type = type.orNull();
            return new DartType(Kind.LIST, null, type, false);
        }
        return new DartType(Kind.DYNAMIC, null, null, false);
    }

    /** The expression that reads a value of this type from {@code expr}, a value jsonDecode returned. */
    private static String read(DartType type, String expr, int depth) {
        String q = type.nullable() ? "?" : "";
        return switch (type.kind()) {
            case INT -> expr + " as int" + q;
            // A whole number in the JSON decodes as an int, which "as double" refuses.
            case DOUBLE -> "(" + expr + " as num" + q + ")" + q + ".toDouble()";
            case NUM -> expr + " as num" + q;
            case STRING -> expr + " as String" + q;
            case BOOL -> expr + " as bool" + q;
            case DYNAMIC -> expr;
            case MAP -> expr + " as Map<String, dynamic>" + q;
            case CLASS -> {
                String read = type.className() + ".fromJson(" + expr + " as Map<String, dynamic>)";
                yield type.nullable() ? expr + " == null ? null : " + read : read;
            }
            case LIST -> {
                if (type.element().kind() == Kind.DYNAMIC) yield expr + " as List<dynamic>" + q;
                String e = depth == 0 ? "e" : "e" + depth;
                yield "(" + expr + " as List<dynamic>" + q + ")" + q + ".map((" + e + ") => "
                      + read(type.element(), e, depth + 1) + ").toList()";
            }
        };
    }

    /** The expression that turns {@code expr} into what jsonEncode writes, or null when it already is. */
    private static String write(DartType type, String expr, int depth) {
        String q = type.nullable() ? "?" : "";
        return switch (type.kind()) {
            case CLASS -> expr + q + ".toJson()";
            case LIST -> {
                String e = depth == 0 ? "e" : "e" + depth;
                String element = write(type.element(), e, depth + 1);
                yield element == null ? null : expr + q + ".map((" + e + ") => " + element + ").toList()";
            }
            default -> null;
        };
    }

    /** A single-quoted Dart literal: {@code $} would start an interpolation. */
    static String stringLiteral(String value) {
        StringBuilder out = new StringBuilder(value.length() + 2).append('\'');
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '\'' -> out.append("\\'");
                case '\\' -> out.append("\\\\");
                case '$' -> out.append("\\$");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20 || c == 0x7F || Character.isSurrogate(c))
                        out.append(String.format(Locale.ROOT, "\\u%04X", (int) c));
                    else out.append(c);
                }
            }
        }
        return out.append('\'').toString();
    }
}
